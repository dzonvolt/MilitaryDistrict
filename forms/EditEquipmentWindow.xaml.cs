namespace MilitaryDistrict.forms
{
    /// <summary>
    /// Логика взаимодействия для EditEquipmentWindow.xaml
    /// </summary>
    public partial class EditEquipmentWindow : Window
    {
        public equipment _equipment;

        public EditEquipmentWindow(equipment _equipment)
        {
            InitializeComponent();
            this.DataContext = _equipment;
            this._equipment = _equipment;
        }

        private void CancelButton_Click(object sender, RoutedEventArgs e)
        {
            this.DialogResult = false;
        }

        private void SaveButton_Click(object sender, RoutedEventArgs e)
        {

            if (
                string.IsNullOrWhiteSpace(_equipment.name) ||
                string.IsNullOrWhiteSpace(_equipment.specs)
            )
            {
                MessageBox.Show("Пожалуйста, заполните все поля.", "Ошибка", MessageBoxButton.OK, MessageBoxImage.Error);
                return;
            }

            this.DialogResult = true;
        }
    }
}

